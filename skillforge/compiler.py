"""SkillCompiler — exports the selected architecture as a Claude-compatible Skill package.

Layout:
    <name>/
      SKILL.md                 frontmatter (name, description) + usage + measured quality + limits
      manifest.json            provenance, model config, seed, metrics, sha256 of every file
      scripts/skill.py         standalone runtime (stdlib; LLM stages via Claude Code `claude -p`)
      scripts/sandbox_runner.py
      scripts/skill_ir.json    the exact IR that was evaluated
      scripts/tools.json       sandboxed tool definitions (if any)
      scripts/components/*.py  readable copies of every code stage
      references/spec.json, references/report.md, references/evaluation.json
      tests/test_skill.py, tests/regression_cases.json
"""

from __future__ import annotations

import hashlib
import json
import platform
import shutil
import sys
import time
from pathlib import Path
from typing import Any

from .domains.base import DomainPlugin, Scenario
from .ir import CodeComponent, SkillIR
from .spec import SkillSpec

TEST_TEMPLATE = '''"""Regression + invariant tests generated by SkillForge for this skill.

Cases are drawn from the *validation* split. `expected_pass` cases must keep
producing the recorded correct output; every case must satisfy the hard
invariants that were enforced during the search.
"""

import json
import subprocess
import sys
from pathlib import Path

import pytest

ROOT = Path(__file__).resolve().parents[1]
CASES = json.loads((Path(__file__).parent / "regression_cases.json").read_text())
REQUIRED = {required}


def run_skill(doc):
    p = subprocess.run([sys.executable, str(ROOT / "scripts" / "skill.py")], input=json.dumps(doc),
                       capture_output=True, text=True, timeout=120)
    assert p.returncode == 0, p.stderr
    return json.loads(p.stdout)


@pytest.mark.parametrize("case", CASES, ids=[c["id"] for c in CASES])
def test_case(case):
    out = run_skill(case["input"])
    exp = case["expected"]
    assert out["status"] in ("valid", "invalid", "needs_review")
    # hard invariant: never approve a document whose correct status is not valid
    if exp["status"] != "valid":
        assert out["status"] != "valid"
    # hard invariant: no fabrication of absent required fields
    for k in set(exp.get("_absent", [])) & REQUIRED:
        assert out.get(k) is None, k
    # hard invariant: status=valid implies arithmetic consistency
    if out["status"] == "valid":
        assert abs(out["subtotal"] + out["tax"] - out["total"]) <= 0.011
    if "llm_unavailable" in (out.get("issues") or []):
        # the LLM stage is needed for this case but the `claude` CLI is not installed: the skill failed
        # closed for the fields it could not establish. Invariants above still hold; exact-output regression
        # needs Claude Code.
        pytest.skip("LLM stage unavailable (install Claude Code to run this regression case)")
    if case["expected_pass"]:
        assert out["status"] == exp["status"]
        for k in ("invoice_number", "date", "total"):
            assert out.get(k) == exp.get(k), k
'''


def sha256(path: Path) -> str:
    return hashlib.sha256(path.read_bytes()).hexdigest()


class SkillCompiler:
    def __init__(self, spec: SkillSpec, plugin: DomainPlugin):
        self.spec = spec
        self.plugin = plugin

    def compile(self, ir: SkillIR, out_dir: Path, *, run_id: str, seed: int, report_md: str,
                evaluation: dict[str, Any], regression: list[tuple[Scenario, bool]], provider: str,
                simulated: bool, dependencies: dict[str, str]) -> Path:
        root = Path(out_dir) / self.spec.name
        if root.exists():
            shutil.rmtree(root)
        (root / "scripts" / "components").mkdir(parents=True)
        (root / "references").mkdir()
        (root / "tests").mkdir()
        here = Path(__file__).resolve().parent
        shutil.copyfile(here / "export_runtime.py", root / "scripts" / "skill.py")
        shutil.copyfile(here / "sandbox_runner.py", root / "scripts" / "sandbox_runner.py")
        (root / "scripts" / "skill_ir.json").write_text(ir.model_dump_json(indent=2))
        used_tools = sorted({t for c in ir.llm_components() for t in c.tools})
        if used_tools:
            lib = self.plugin.tool_library()
            (root / "scripts" / "tools.json").write_text(json.dumps({t: lib[t] for t in used_tools}, indent=2))
        seen: dict[str, int] = {}
        for c in ir.walk():
            if isinstance(c, CodeComponent):
                seen[c.name] = seen.get(c.name, 0) + 1
                fname = c.name + (f"_{seen[c.name]}" if seen[c.name] > 1 else "") + ".py"
                (root / "scripts" / "components" / fname).write_text(
                    f"# params: {json.dumps(c.params)}\n# origin: {c.origin}, role: {c.role}\n{c.source.lstrip()}")
        (root / "references" / "spec.json").write_text(self.spec.model_dump_json(indent=2))
        (root / "references" / "report.md").write_text(report_md)
        (root / "references" / "evaluation.json").write_text(json.dumps(evaluation, indent=2, default=str))
        cases = [{"id": s.id, "family": s.family, "input": s.input, "expected": s.expected, "expected_pass": ok}
                 for s, ok in regression]
        (root / "tests" / "regression_cases.json").write_text(json.dumps(cases, indent=1))
        (root / "tests" / "test_skill.py").write_text(
            TEST_TEMPLATE.replace("{required}", repr({"vendor", "invoice_number", "date", "total"})))
        (root / "SKILL.md").write_text(self._skill_md(ir, evaluation, simulated))
        files = sorted(p for p in root.rglob("*") if p.is_file())
        manifest = {
            "name": self.spec.name, "version": "1.0.0", "created_at": time.strftime("%Y-%m-%dT%H:%M:%SZ", time.gmtime()),
            "generator": "skillforge 0.1.0", "run_id": run_id, "candidate_id": ir.id, "parents": ir.parents,
            "architecture": ir.architecture().value, "fingerprint": ir.fingerprint(), "seed": seed,
            "provider": provider, "llm_results_simulated": simulated,
            "models": [{"component": c.name, "model": c.model, "effort": c.effort, "max_tokens": c.max_tokens,
                        "tools": c.tools} for c in ir.llm_components()],
            "runtime": {"python": ">=3.10", "stdlib_only_code": True,
                        "llm_runtime": "Claude Code CLI (claude -p)" if ir.llm_components() else None},
            "build_environment": {"python": sys.version.split()[0], "platform": platform.platform(), **dependencies},
            "metrics": evaluation.get("holdout", {}).get("metrics", {}),
            "files": {str(p.relative_to(root)): sha256(p) for p in files},
        }
        (root / "manifest.json").write_text(json.dumps(manifest, indent=2, default=str))
        return root

    def _skill_md(self, ir: SkillIR, ev: dict[str, Any], simulated: bool) -> str:
        hold = ev.get("holdout", {})
        m = hold.get("metrics", {})
        ci = hold.get("intervals", {})
        llms = ir.llm_components()
        desc = (f"{self.spec.summary} Use when processing invoice text to obtain validated fields and a "
                f"valid/invalid/needs_review decision.")
        lines = [
            "---",
            f"name: {self.spec.name}",
            f"description: {desc}",
            "---",
            "",
            f"# {self.spec.name}",
            "",
            self.plugin.render_skill_instructions(self.spec, ir),
            "",
            "## Architecture",
            f"- Class: `{ir.architecture().value}` (candidate `{ir.id}`, fingerprint `{ir.fingerprint()}`)",
            f"- Stages: {' → '.join(c.name for c in ir.components)}",
            f"- LLM stages: {', '.join(f'{c.name} ({c.model})' for c in llms) if llms else 'none — pure Python stdlib'}",
            "",
            "## Measured quality (independent holdout, evaluated once)",
            "",
            "| metric | value | 95% interval |",
            "|---|---|---|",
        ]
        for k in ("pass_rate", "robustness", "status_accuracy", "field_accuracy", "hard_violation_rate",
                  "cost_per_item_usd", "latency_ms_p95"):
            if k in m:
                iv = ci.get(k)
                lines.append(f"| {k} | {m[k]:.4g} | {f'[{iv[0]:.3f}, {iv[1]:.3f}]' if iv else '—'} |")
        lines += ["", "## Limitations", ""]
        if simulated:
            lines.append("- **LLM-stage results were produced by a simulated model** (offline mock); they are not "
                         "measurements of any real model. Re-run SkillForge with a real provider before relying on them.")
        for lim in self.spec.verification_limits:
            lines.append(f"- {lim}")
        lines += ["- Results come from synthetic scenarios; they are not empirical evidence of real-world accuracy.",
                  "- The search is heuristic; no claim of global optimality is made.",
                  "", "See `references/report.md` for the full evaluation report."]
        return "\n".join(lines) + "\n"
